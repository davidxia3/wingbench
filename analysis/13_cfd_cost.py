#!/usr/bin/env python3
"""Average CFD cost per evaluation across both studies.

Every study uses the same definition: wall time is the mesh attempt plus every
flow-condition attempt, and processor-core seconds are that wall time times the
16 cores each CFD job uses. Evaluations without a published result have no
timing and are left out of the average.

Input:
  data/episodes.csv   processor-core seconds and timed evaluations per episode
Output:
  paper/cfd_cost_numbers.tex
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "paper/cfd_cost_numbers.tex"
CORES = 16


def comma(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main():
    episodes = list(csv.DictReader((ROOT / "data/episodes.csv").open()))
    study = {s: [e for e in episodes if e["study"] == s] for s in ("baseline", "agent")}

    baseline_seconds = sum(float(e["cfd_core_seconds"]) for e in study["baseline"])
    baseline_n = sum(int(e["timed_evaluations"]) for e in study["baseline"])
    agent_seconds = sum(float(e["cfd_core_seconds"]) for e in study["agent"])
    agent_n = sum(int(e["timed_evaluations"]) for e in study["agent"])

    hours = (baseline_seconds + agent_seconds) / 3600
    n = baseline_n + agent_n
    lines = [
        "% Generated by analysis/13_cfd_cost.py. Processor-core hours per CFD",
        "% evaluation = (mesh attempt + every condition attempt) wall time x 16 cores.",
        f"\\newcommand{{\\AvgCoreHoursPerEvalOverall}}{{{hours / n:.1f}}}",
        f"\\newcommand{{\\AvgCoreHoursPerEvalAgent}}{{{agent_seconds / 3600 / agent_n:.1f}}}",
        f"\\newcommand{{\\CoreHoursOverall}}{{{comma(round(hours))}}}",
        f"\\newcommand{{\\TimedEvaluationsOverall}}{{{comma(n)}}}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(OUTPUT)
    for line in lines[2:-1]:
        print(" ", line)


if __name__ == "__main__":
    main()

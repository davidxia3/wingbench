#!/usr/bin/env python3
"""05_paper_macros.py — regenerate paper/generated/macros.tex from analysis outputs.

Every number the prose cites inline comes through these macros, so re-running
analysis/run_all.sh updates the draft in place. No hand-computed numbers.
"""
from __future__ import annotations

import json

import pandas as pd

from common import (
    CONFIGS,
    CONFIG_SHORT,
    METHODS,
    METHOD_SHORT,
    OUT,
    WORKSPACE,
    load_meta,
    tentative_banner,
)

GEN = WORKSPACE / "analysis" / "out" / "macros"

MKEY = {
    "static-precommitted-cmaes-v2-pilot": "Static",
    "conventional-adaptive-cmaes-v2-pilot": "Adaptive",
    "fsd-cma-v1-port-v2-pilot": "Fsd",
    "checkpointed-de-feedback-v2-pilot": "De",
}
CKEY = {
    "superwing-load-low-cl015": "Low",
    "superwing-load-nominal-cl041": "Nominal",
    "superwing-load-high-cl066": "High",
}
CAT_KEY = {
    "success": "Delivered",
    "mesh failed (inconclusive)": "MeshInconclusive",
    "mesh failed (unmeshable)": "Unmeshable",
    "solver timeout": "Timeout",
    "no solver result": "Infra",
    "other": "Other",
}


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def pct(x) -> str:
    return f"{100.0 * float(x):.0f}"


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    meta = load_meta()
    ystats = json.loads((OUT / "yield_stats.json").read_text())
    gstats = json.loads((OUT / "gap_stats.json").read_text())
    verification = json.loads((OUT / "verification.json").read_text())
    ck32 = pd.read_csv(OUT / "tables" / "tab_ck32.csv")
    replay = pd.read_csv(OUT / "replay_meta.csv")
    episodes = pd.read_csv(OUT / "episodes.csv")

    n_term = int(meta.get("episodes_terminal", 0))
    lines = [
        "% AUTO-GENERATED by analysis/05_paper_macros.py — do not edit by hand.",
        macro("CampaignBanner", tentative_banner().replace("_", r"\_")),
        macro("SnapshotSerial", meta["serial"]),
        macro("SnapshotRefreshed", meta["refreshed_at_utc"]),
        macro("CampaignComplete", "true" if meta.get("campaign_complete") else "false"),
        macro("NGrades", meta["n_grade_records"]),
        macro("NEpisodesTerminal", n_term),
        macro("NEpisodesRemaining", 120 - n_term),
        macro("NOnlineGrades", verification["n_online"]),
        macro("NHiddenGrades", verification["n_hidden"]),
        macro("NNullGrades", verification["n_null_value"]),
        macro("PctNullGrades",
              f"{100.0 * verification['n_null_value'] / verification['n_grade_records']:.0f}"),
        macro("OverallOnlineDeliveryPct", pct(ystats["overall_online_delivery"])),
        macro("OverallFreshHiddenDeliveryPct", pct(ystats["overall_hidden_fresh_delivery"])),
    ]
    # online outcome category counts
    for cat, key in CAT_KEY.items():
        lines.append(macro(f"NOnline{key}", ystats["online_category_counts"].get(cat, 0)))

    # per-cell online delivery and fresh-hidden delivery
    for cfg in CONFIGS:
        for m in METHODS:
            v = ystats["per_cell_online_delivery"].get(f"{cfg}|{m}")
            if v is not None and v == v:
                lines.append(macro(f"OnlineDelivery{CKEY[cfg]}{MKEY[m]}Pct", pct(v)))
            cell = gstats["cells"].get(f"{cfg}|{m}", {})
            fh = cell.get("fresh_hidden_delivery")
            lines.append(macro(f"FreshDel{CKEY[cfg]}{MKEY[m]}Pct",
                               pct(fh) if fh is not None else "--"))
            lines.append(macro(f"FreshN{CKEY[cfg]}{MKEY[m]}", cell.get("n_fresh_hidden", 0)))

    # checkpoint-32 per cell (from tab_ck32.csv; display names -> keys)
    inv_c = {v: k for k, v in CONFIG_SHORT.items()}
    inv_m = {v: k for k, v in METHOD_SHORT.items()}
    for _, r in ck32.iterrows():
        cfg, m = inv_c[r["config"]], inv_m[r["method"]]
        tag = f"{CKEY[cfg]}{MKEY[m]}"
        lines.append(macro(f"CkN{tag}", int(r["n"])))
        lines.append(macro(f"CkDel{tag}Pct", pct(r["delivery"]) if r["n"] > 0 else "--"))
        lines.append(macro(f"CkDel{tag}Frac",
                           f"{int(round(r['delivery'] * r['n']))}/{int(r['n'])}" if r["n"] > 0 else "--"))
        lines.append(macro(f"CkVal{tag}",
                           f"{r['value_mean']:.1f}" if pd.notna(r["value_mean"]) else "--"))

    # fresh hidden grades consumed per terminal episode, per method (cost of honesty)
    term_idx = episodes[episodes["status_terminal"] == True]["episode_index"]  # noqa: E712
    fr = replay[replay["episode_index"].isin(term_idx)]
    for m in METHODS:
        sub = fr[fr["method"] == m]["fresh_checkpoint_grades_used"]
        lines.append(macro(f"FreshGrades{MKEY[m]}", f"{sub.mean():.1f}" if len(sub) else "--"))
        lines.append(macro(f"FreshGradesN{MKEY[m]}", len(sub)))

    (GEN / "macros.tex").write_text("\n".join(lines) + "\n")
    # raw-value twin read by later scripts (no LaTeX escaping)
    raw = {}
    for ln in lines[1:]:
        name = ln[len("\\newcommand{\\"):ln.index("}")]
        raw[name] = ln[ln.index("}{") + 2:-1]
    raw["CampaignBanner"] = tentative_banner()
    (GEN / "macros.json").write_text(json.dumps(raw, indent=1))
    print(f"wrote paper/generated/macros.tex + macros.json ({len(lines)} macros)")


if __name__ == "__main__":
    main()

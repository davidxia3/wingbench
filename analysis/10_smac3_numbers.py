#!/usr/bin/env python3
"""Generate paper/smac3_numbers.tex from saved results.

Every SMAC3 number in the paper, and every number that combines the SMAC3 arm
with the four sealed baselines, is written here from files rather than typed
in. Rerun after any change to the SMAC3 data or the sealed analysis outputs.

Inputs
  data/episodes.csv                                    SMAC3 CFD cost per episode
  data/evaluations.csv                                 SMAC3 online grades
  data/recommendations.csv                             SMAC3 checkpoint recommendations
  analysis/out/curves.csv                              sealed checkpoint provenance
  analysis/out/grades.csv                              sealed grades (max L/D)
  analysis/out/replay_meta.csv                         sealed CPU seconds
  analysis/out/macros/macros.json                      sealed grade counts

Writes paper/smac3_numbers.tex
"""
from __future__ import annotations

import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "analysis" / "out"
TARGET = ROOT / "paper" / "smac3_numbers.tex"
CORES = 16


def comma(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> int:
    def smac3(name):
        return [r for r in csv.DictReader((DATA / f"{name}.csv").open()) if r["method"] == "SMAC3"]

    smac_episodes = smac3("episodes")
    smac_grades = [r for r in smac3("evaluations") if r["kind"] == "online"]
    curve = smac3("recommendations")
    sealed = json.loads((OUT / "macros" / "macros.json").read_text())
    sealed_curve = list(csv.DictReader((OUT / "curves.csv").open()))
    sealed_grades = list(csv.DictReader((OUT / "grades.csv").open()))
    replay = list(csv.DictReader((OUT / "replay_meta.csv").open()))

    # online yield per task
    s = {}
    for task in ("low", "nominal", "high"):
        rows = [r for r in smac_grades if r["task"] == task]
        n_ok = sum(r["delivered"] == "True" for r in rows)
        s[task] = {"evals": len(rows), "delivered": n_ok, "delivered_pct": round(100 * n_ok / len(rows), 1)}
    summary = {"total_evals": len(smac_grades), "tasks": s,
               "delivered": sum(r["delivered"] == "True" for r in smac_grades)}

    # checkpoint 32: the recommendation graded at the end of each episode
    t = {}
    for task in ("low", "nominal", "high"):
        final = [r for r in curve if r["task"] == task and r["checkpoint"] == "32"]
        values = [float(r["ld"]) for r in final if r["delivered"] == "True"]
        t[task] = {"n": len(final),
                   "delivery": round(len(values) / len(final), 4),
                   "value_mean": round(statistics.mean(values), 4),
                   "value_median": round(statistics.median(values), 4)}

    smac_cpu = sum(float(e["cfd_core_seconds"]) for e in smac_episodes)
    smac_timed = sum(int(e["timed_evaluations"]) for e in smac_episodes)

    n_sealed = int(sealed["NGrades"])
    n_sealed_online = int(sealed["NOnlineGrades"])
    n_sealed_hidden = int(sealed["NHiddenGrades"])
    n_smac_online = summary["total_evals"]
    n_smac_fresh = sum(1 for r in curve if r["graded_by"] == "private")
    n_smac_reused = sum(1 for r in curve if r["graded_by"] == "online")
    n_sealed_reused = sum(1 for r in sealed_curve if r["provenance"] == "reused_online_visible")
    n_sealed_fresh = sum(1 for r in sealed_curve if r["provenance"] == "fresh_hidden")
    assert n_sealed_fresh == n_sealed_hidden, (n_sealed_fresh, n_sealed_hidden)
    assert n_sealed_online + n_sealed_hidden == n_sealed

    max_sealed = max(float(r["conditional_value"]) for r in sealed_grades
                     if r["delivery"] == "True" and r["conditional_value"])
    max_smac = max(float(r["ld"]) for r in smac_grades if r["delivered"] == "True" and r["ld"])

    sealed_cpu = sum(float(r["evaluator_cpu_seconds"]) for r in replay)
    n_timed = n_sealed + smac_timed
    n_all = n_sealed + n_smac_online + n_smac_fresh
    all_wall_s = (sealed_cpu + smac_cpu) / CORES
    mean_wall_min = all_wall_s / n_timed / 60
    core_hours = (sealed_cpu + smac_cpu) / 3600

    low, nom, high = t["low"], t["nominal"], t["high"]
    slow, snom, shigh = s["low"], s["nominal"], s["high"]

    lines = [
        "% AUTO-GENERATED by analysis/10_smac3_numbers.py. Do not edit.",
        "% Every value here is computed from saved results.",
        "",
        f"\\newcommand{{\\TotalEpisodes}}{{{120 + 30}}}",
        f"\\newcommand{{\\TotalCFDEvaluations}}{{{comma(n_all)}}}",
        f"\\newcommand{{\\OriginalEpisodes}}{{120}}",
        f"\\newcommand{{\\OriginalCFDEvaluations}}{{{comma(n_sealed)}}}",
        f"\\newcommand{{\\OnlineEvaluationsAll}}{{{comma(n_sealed_online + n_smac_online)}}}",
        f"\\newcommand{{\\NewRecommendationEvaluationsAll}}{{{n_sealed_fresh + n_smac_fresh}}}",
        f"\\newcommand{{\\CheckpointRecordsAll}}{{{comma(len(sealed_curve) + len(curve))}}}",
        f"\\newcommand{{\\ReusedGradesAll}}{{{n_sealed_reused + n_smac_reused}}}",
        f"\\newcommand{{\\SMACEpisodes}}{{30}}",
        f"\\newcommand{{\\SMACOnlineEvaluations}}{{{n_smac_online}}}",
        f"\\newcommand{{\\SMACFreshRecommendationEvaluations}}{{{n_smac_fresh}}}",
        f"\\newcommand{{\\SMACReusedRecommendations}}{{{n_smac_reused}}}",
        f"\\newcommand{{\\SMACCheckpointRecords}}{{{len(curve)}}}",
        f"\\newcommand{{\\SMACDistinctRecommended}}{{{len({r['wing'] for r in curve if r['wing']})}}}",
        f"\\newcommand{{\\SMACAllEvaluations}}{{{n_smac_online + n_smac_fresh}}}",
        f"\\newcommand{{\\SMACOnlineDelivered}}{{{summary['delivered']}}}",
        f"\\newcommand{{\\SMACOnlineDeliveryPct}}{{{100 * summary['delivered'] / n_smac_online:.1f}\\%}}",
        "",
        f"\\newcommand{{\\SMACLowOnlineDelivered}}{{{slow['delivered']}}}",
        f"\\newcommand{{\\SMACNomOnlineDelivered}}{{{snom['delivered']}}}",
        f"\\newcommand{{\\SMACHighOnlineDelivered}}{{{shigh['delivered']}}}",
        f"\\newcommand{{\\SMACLowOnlineDelivery}}{{{slow['delivered_pct']:.1f}\\%}}",
        f"\\newcommand{{\\SMACNomOnlineDelivery}}{{{snom['delivered_pct']:.1f}\\%}}",
        f"\\newcommand{{\\SMACHighOnlineDelivery}}{{{shigh['delivered_pct']:.1f}\\%}}",
        f"\\newcommand{{\\SMACLowOnlineRate}}{{{slow['delivered'] / slow['evals']:.2f}}}",
        f"\\newcommand{{\\SMACNomOnlineRate}}{{{snom['delivered'] / snom['evals']:.2f}}}",
        f"\\newcommand{{\\SMACHighOnlineRate}}{{{shigh['delivered'] / shigh['evals']:.2f}}}",
        "",
        f"\\newcommand{{\\SMACLowFinalRate}}{{{low['delivery']:.2f}}}",
        f"\\newcommand{{\\SMACLowFinalMean}}{{{low['value_mean']:.2f}}}",
        f"\\newcommand{{\\SMACLowFinalMedian}}{{{low['value_median']:.2f}}}",
        f"\\newcommand{{\\SMACLowFinalDelivered}}{{{round(low['delivery'] * low['n'])}}}",
        f"\\newcommand{{\\SMACNominalFinalRate}}{{{nom['delivery']:.2f}}}",
        f"\\newcommand{{\\SMACNominalFinalMean}}{{{nom['value_mean']:.2f}}}",
        f"\\newcommand{{\\SMACNominalFinalMedian}}{{{nom['value_median']:.2f}}}",
        f"\\newcommand{{\\SMACNominalFinalDelivered}}{{{round(nom['delivery'] * nom['n'])}}}",
        f"\\newcommand{{\\SMACHighFinalRate}}{{{high['delivery']:.2f}}}",
        f"\\newcommand{{\\SMACHighFinalMean}}{{{high['value_mean']:.2f}}}",
        f"\\newcommand{{\\SMACHighFinalMedian}}{{{high['value_median']:.2f}}}",
        f"\\newcommand{{\\SMACHighFinalDelivered}}{{{round(high['delivery'] * high['n'])}}}",
        "",
        f"\\newcommand{{\\MaxObservedLdAll}}{{{max(max_sealed, max_smac):.1f}}}",
        f"\\newcommand{{\\SMACMaxOnlineLd}}{{{max_smac:.2f}}}",
        "",
        "% Resource accounting on the sealed definition: wall = mesh + all condition",
        "% attempts; CPU seconds = wall x 16 cores. Timing is unavailable for the",
        "% SMAC3 evaluations whose evidence record was never published.",
        f"\\newcommand{{\\CoreHoursAll}}{{{comma(round(core_hours))}}}",
        f"\\newcommand{{\\CoreHoursSealed}}{{{comma(round(sealed_cpu / 3600))}}}",
        f"\\newcommand{{\\CoreHoursSMAC}}{{{comma(round(smac_cpu / 3600))}}}",
        f"\\newcommand{{\\AvgCoreHoursPerEvalAll}}{{{core_hours / n_timed:.1f}}}",
        f"\\newcommand{{\\AvgWallMinutesAll}}{{{mean_wall_min:.0f}}}",
        f"\\newcommand{{\\AvgWallHoursAll}}{{{mean_wall_min / 60:.1f}}}",
        f"\\newcommand{{\\AvgWallMinutesSealed}}{{{sealed_cpu / CORES / n_sealed / 60:.0f}}}",
        f"\\newcommand{{\\AvgWallMinutesSMAC}}{{{smac_cpu / CORES / smac_timed / 60:.0f}}}",
        f"\\newcommand{{\\TimedEvaluations}}{{{comma(n_timed)}}}",
        f"\\newcommand{{\\UntimedEvaluations}}{{{n_all - n_timed}}}",
        "",
    ]
    TARGET.write_text("\n".join(lines))
    print(f"wrote {TARGET.relative_to(ROOT)}")
    for line in lines:
        if line.startswith("\\newcommand"):
            print("  " + line[len("\\newcommand"):])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""03_recommendation_curves.py — the honest measurement axis.

Per checkpoint: (a) delivery probability of the checkpoint recommendation and
(b) conditional L/D among delivered recommendations, per method x config, from
the independent-replay recommendation curves (reuse resolved).  The x axis is
the frozen normalized axis log2(q+1)/log2(33).

Outputs: figures/fig_recommendation_curves.pdf
         out/tables/tab_ck32.tex (+csv)
         out/recommendation_stats.json
"""
from __future__ import annotations

import json
import math

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from common import (
    CONFIGS,
    CONFIG_SHORT,
    FIGURES,
    HIDDEN_CHECKPOINTS,
    METHODS,
    METHOD_COLOR,
    METHOD_LS,
    METHOD_MARKER,
    METHOD_SHORT,
    OUT,
    ensure_dirs,
    load_episodes,
    snapshot_stamp,
    stamp_axes,
    tentative_banner,
    write_table,
)


def xpos(q: int) -> float:
    return math.log2(q + 1) / math.log2(33)


def main() -> None:
    ensure_dirs()
    curves = pd.read_csv(OUT / "curves.csv")
    ep = load_episodes()
    term = ep.set_index("episode_index")["status_terminal"].fillna(False)
    curves["terminal_ep"] = curves["episode_index"].map(term)

    fig, axes = plt.subplots(2, 3, figsize=(11.5, 6.2), sharex=True)
    stats: dict = {"stamp": snapshot_stamp(), "cells": {}}

    for j, cfg in enumerate(CONFIGS):
        ax_d, ax_v = axes[0, j], axes[1, j]
        for m in METHODS:
            sub = curves[(curves.config == cfg) & (curves.method == m)]
            xs, del_rate, val_mean, ns, nsd = [], [], [], [], []
            for ck in HIDDEN_CHECKPOINTS:
                pts = sub[sub.checkpoint == ck]
                if not len(pts):
                    continue
                xs.append(xpos(ck))
                del_rate.append(pts["delivery"].mean())
                delivered = pts[pts.delivery == True]  # noqa: E712
                val_mean.append(delivered["conditional_value"].mean()
                                if len(delivered) else np.nan)
                ns.append(len(pts))
                nsd.append(len(delivered))
            ax_d.plot(xs, del_rate, color=METHOD_COLOR[m], lw=1.6,
                      ls=METHOD_LS[m], marker=METHOD_MARKER[m], ms=3.5,
                      label=METHOD_SHORT[m])
            ax_v.plot(xs, val_mean, color=METHOD_COLOR[m], lw=1.6,
                      ls=METHOD_LS[m], marker=METHOD_MARKER[m], ms=3.5)
            stats["cells"][f"{cfg}|{m}"] = {
                "checkpoints": [int(c) for c in HIDDEN_CHECKPOINTS if len(sub[sub.checkpoint == c])],
                "n_episodes_at_ck": ns,
                "n_delivered_at_ck": nsd,
                "delivery": [round(float(v), 4) for v in del_rate],
                "value_mean": [None if pd.isna(v) else round(float(v), 4) for v in val_mean],
            }
        for ax in (ax_d, ax_v):
            ax.set_xticks([xpos(c) for c in HIDDEN_CHECKPOINTS])
            ax.set_xticklabels([str(c) for c in HIDDEN_CHECKPOINTS], fontsize=7)
        ax_d.set_title(CONFIG_SHORT[cfg], fontsize=9.5)
        ax_d.set_ylim(-0.03, 1.03)
        ax_v.set_ylim(14, 36)
        ax_v.set_xlabel("CFD evaluations used, k (log scale)")
    axes[0, 0].set_ylabel("fraction of recommendations\nevaluated successfully")
    axes[1, 0].set_ylabel("L/D of successful recommendations")
    axes[0, 0].legend(fontsize=7, loc="upper left")
    fig.suptitle("Recommended design after k CFD evaluations (held-out evaluation)",
                 fontsize=11)
    fig.tight_layout(rect=(0, 0.015, 1, 1))
    stamp_axes(fig, "unfinished episodes contribute the checkpoints they have reached")
    fig.savefig(FIGURES / "fig_recommendation_curves.pdf", bbox_inches="tight")
    fig.savefig(FIGURES / "fig_recommendation_curves.png", dpi=180, bbox_inches="tight")
    plt.close(fig)

    # ---------------------------------------------------------------- ck32 table
    ck32 = curves[curves.checkpoint == 32]
    rows = []
    for cfg in CONFIGS:
        for m in METHODS:
            pts = ck32[(ck32.config == cfg) & (ck32.method == m)]
            delivered = pts[pts.delivery == True]  # noqa: E712
            rows.append({
                "config": CONFIG_SHORT[cfg], "method": METHOD_SHORT[m],
                "n": len(pts),
                "delivery": pts["delivery"].mean() if len(pts) else np.nan,
                "value_mean": delivered["conditional_value"].mean() if len(delivered) else np.nan,
                "value_median": delivered["conditional_value"].median() if len(delivered) else np.nan,
            })
    t32 = pd.DataFrame(rows)
    lines = [
        "% AUTO-GENERATED by analysis/03_recommendation_curves.py — do not edit",
        f"% {tentative_banner()}",
        r"\begin{tabular}{llcccc}", r"\toprule",
        r"task & method & $n$ & success rate & mean L/D & median L/D \\",
        r"\midrule",
    ]
    for _, r in t32.iterrows():
        v = "--" if pd.isna(r.value_mean) else f"{r.value_mean:.2f}"
        vm = "--" if pd.isna(r.value_median) else f"{r.value_median:.2f}"
        d = "--" if pd.isna(r.delivery) else f"{r.delivery:.2f}"
        lines.append(f"{r.config} & {r.method} & {int(r.n)} & {d} & {v} & {vm} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table("tab_ck32", "\n".join(lines), t32.set_index(["config", "method"]))

    (OUT / "recommendation_stats.json").write_text(json.dumps(stats, indent=1))
    print("checkpoint-32 snapshot (n episodes reaching ck32 so far):")
    print(t32.to_string(index=False))


if __name__ == "__main__":
    main()
